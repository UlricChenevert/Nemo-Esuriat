// Turns a coloured-ASCII HTML export into a TypeScript art module.
//
// The game fetches nothing -- it is plain ESM served straight to the browser --
// so a picture has to become a module rather than an asset loaded at runtime.
// This does that conversion once, at author time.
//
//   node Tools/ConvertAsciiArt.mjs <input.html> <Configuration/TitleArt.ts> [ExportName]
//
// Input is expected to be a run of <span style="color:#rrggbb">G</span> cells with
// <br> between rows, which is what the usual ASCII-art converters emit.
//
// Colour is reduced to twelve bits on the way through. A backdrop drawn in a
// handful of glyph shapes cannot show the difference, it halves the size of the
// generated module, and it collapses thousands of near-identical shades into a
// few hundred before palette fitting ever runs.

import { readFileSync, writeFileSync } from "node:fs"

const [inputPath, outputPath, exportName = "TitleArt"] = process.argv.slice(2)

if (!inputPath || !outputPath) {
    console.error("usage: node Tools/ConvertAsciiArt.mjs <input.html> <output.ts> [ExportName]")
    process.exit(1)
}

const html = readFileSync(inputPath, "utf8")

// Everything between <body> and </body>, so the <style> block's own colour
// declarations cannot be mistaken for cells.
const bodyMatch = html.match(/<body[^>]*>([\s\S]*)<\/body>/i)
const body = bodyMatch ? bodyMatch[1] : html

const rows = body
    .split(/<br\s*\/?>/i)
    .map((row) => [...row.matchAll(/<span[^>]*color\s*:\s*#([0-9a-fA-F]{6})[^>]*>([\s\S]*?)<\/span>/g)])
    .filter((cells) => cells.length > 0)
    .map((cells) => cells.map(([, hex, glyph]) => {
        // High nibble per channel. Doubling on the way back out is what keeps
        // white white, so the reader must expand rather than shift.
        const short = hex[0] + hex[2] + hex[4]

        // One character per cell. A multi-character span is an entity or an
        // escape the source should not have contained.
        const character = glyph.length === 1 ? glyph : " "

        return short.toLowerCase() + character
    }).join(""))

if (rows.length === 0) {
    console.error(`No cells found in ${inputPath}. Expected <span style="color:#rrggbb">G</span> runs.`)
    process.exit(1)
}

const width = rows[0].length / 4

for (const [index, row] of rows.entries()) {
    if (row.length === rows[0].length) continue

    console.error(`Row ${index + 1} has ${row.length / 4} cells; row 1 has ${width}. The art must be rectangular.`)
    process.exit(1)
}

const module = `import { MultiTileRepresentation } from "../Contracts/Components/MultiTileRepresentation.ts";
import { BuildAsciiArt } from "../Utilities/AsciiArtUtilities.ts";

/**
 * GENERATED by Tools/ConvertAsciiArt.mjs from ${inputPath.replace(/\\\\/g, "/")}. Do not hand-edit;
 * re-run the converter instead.
 *
 * ${width} columns by ${rows.length} rows. Four characters per cell: three hex digits
 * of colour, then the glyph. See Utilities/AsciiArtUtilities for the format and
 * for how this becomes a palette.
 */
const ${exportName}Rows : readonly string[] = [
${rows.map((row) => `    "${row}"`).join(",\n")}
]

/** Built once and shared: a picture has no per-instance state. */
export const ${exportName} : MultiTileRepresentation = BuildAsciiArt(${exportName}Rows)
`

writeFileSync(outputPath, module)

console.log(`Wrote ${outputPath}: ${width}x${rows.length} cells (${rows.length * width} total).`)
